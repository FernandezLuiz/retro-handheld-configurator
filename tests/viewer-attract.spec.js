import { test, expect } from '@playwright/test'

const inspect = page => page.evaluate(async () => {
  const { inspectViewer } = await import('/src/scene/viewer.js')
  return inspectViewer(document.querySelector('#scene'))
})

test('viewer keeps the camera above scene floors, limits zoom-out, and yields attract rotation to input', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('#play')).toBeEnabled()
  await expect(page.locator('.product-info')).toHaveCount(0)
  const canvas = page.locator('#scene canvas')
  const box = await canvas.boundingBox()
  const center = { x: box.x + box.width / 2, y: box.y + box.height / 2 }
  const fittedDistance = (await inspect(page)).orbitLimits.currentDistance
  await page.mouse.move(center.x, center.y)
  await page.mouse.down()
  await page.mouse.move(center.x, center.y - box.height * .75, { steps: 16 })
  await page.mouse.up()
  await page.waitForTimeout(400)
  let state = await inspect(page)
  expect(state.camera[1]).toBeGreaterThan(state.target[1])
  expect(state.orbitLimits.maxPolarAngle).toBeLessThan(Math.PI / 2)
  const polarAngle = Math.acos((state.camera[1] - state.target[1]) / state.orbitLimits.currentDistance)
  expect(polarAngle).toBeGreaterThan(1.35)
  for (const name of ['Studio', 'Retro Desk', 'Arcade', 'Dark Tech']) {
    await page.locator(`[data-option="scene"][data-value="${name}"]`).click()
    await page.locator('.viewport').screenshot({ path: `/tmp/viewer-floor-${name.toLowerCase().replaceAll(' ', '-')}.png` })
    state = await inspect(page)
    expect(state.camera[1]).toBeGreaterThan(state.target[1])
  }
  await page.mouse.move(center.x, center.y)
  await page.mouse.wheel(0, 4000)
  await page.waitForTimeout(600)
  state = await inspect(page)
  expect(state.orbitLimits.maxDistance).toBeCloseTo(fittedDistance, 2)
  expect(state.orbitLimits.currentDistance).toBeLessThanOrEqual(state.orbitLimits.maxDistance + .01)
  for (const name of ['Studio', 'Retro Desk', 'Arcade', 'Dark Tech']) {
    await page.locator(`[data-option="scene"][data-value="${name}"]`).click()
    await page.locator('.viewport').screenshot({ path: `/tmp/viewer-max-zoom-${name.toLowerCase().replaceAll(' ', '-')}.png` })
  }
  await page.setViewportSize({ width: 390, height: 844 })
  const mobileBox = await canvas.boundingBox()
  await page.mouse.move(mobileBox.x + mobileBox.width / 2, mobileBox.y + mobileBox.height / 2)
  await page.mouse.wheel(0, 4000)
  await page.waitForTimeout(400)
  state = await inspect(page)
  expect(state.orbitLimits.currentDistance).toBeLessThanOrEqual(state.orbitLimits.maxDistance + .01)
  expect(state.camera[1]).toBeGreaterThan(state.target[1])
  await page.locator('.viewport').screenshot({ path: '/tmp/viewer-max-zoom-mobile.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.locator('#reset').click()
  await expect.poll(async () => (await inspect(page)).attracting, { timeout: 22000 }).toBe(true)
  await page.mouse.move(center.x + 40, center.y + 40)
  await expect.poll(async () => (await inspect(page)).attracting).toBe(false)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.waitForTimeout(150)
  expect((await inspect(page)).attracting).toBe(false)
  await page.locator('#play').click()
  await expect(page.locator('.play-overlay')).toHaveAttribute('data-phase', 'selecting', { timeout: 10000 })
  await page.screenshot({ path: '/tmp/game-library-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/tmp/game-library-mobile.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.locator('[data-game="vector"]')).toBeVisible()
  await expect(page.locator('[data-game="invaders"]')).toBeVisible()
})
